import {test,expect} from '@playwright/test'
const URL=process.env.ZENITH_REF_TEST_URL||'http://127.0.0.1:8510/'
const companion=page=>page.getByRole('complementary',{name:'The Ref sports companion'})

test('Ref spontaneously throws a silent visual flag while visitors browse Home', async ({page})=>{
  await page.setViewportSize({width:1280,height:900})
  await page.clock.install({time:new Date('2026-10-10T14:00:00.000Z')})
  await page.goto(URL,{waitUntil:'domcontentloaded'})
  const ref=companion(page)
  await expect(ref).toHaveAttribute('data-signal','idle')
  await page.evaluate(()=>{window.__refAudioConstructionCount=0;window.AudioContext=class {
    constructor(){window.__refAudioConstructionCount+=1;throw new Error('audio stub blocked')}
  }})
  await page.clock.runFor(12050)
  await expect(ref).toHaveAttribute('data-origin','auto')
  await expect(ref).toHaveAttribute('data-signal','flag')
  expect(await ref.locator('.zenith-ref-flag').evaluate(el=>getComputedStyle(el).animationName)).toContain('zenith-premium-flag-toss')
  expect(await page.evaluate(()=>window.__refAudioConstructionCount)).toBe(0)
  await page.clock.runFor(2200)
  await expect(ref).toHaveAttribute('data-signal','idle')
  await page.clock.runFor(27100)
  await expect(ref).toHaveAttribute('data-origin','auto')
  await expect(ref).not.toHaveAttribute('data-signal','idle')
  expect(await page.evaluate(()=>window.__refAudioConstructionCount)).toBe(0)
})

