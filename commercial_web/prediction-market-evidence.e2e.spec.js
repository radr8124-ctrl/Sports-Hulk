import {test,expect} from '@playwright/test'
const BASE=process.env.ZENITH_PREDICTION_URL||'http://127.0.0.1:8510/'
for(const width of [320,390,430]) {
 test(`matched NFL evidence at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:844})
  await page.goto(BASE+'#prediction-markets',{waitUntil:'domcontentloaded'})
  await expect(page.getByRole('heading',{name:'Prediction Markets',exact:true})).toBeVisible()
  await expect(page.getByText('Net ROI · not measured',{exact:true})).toBeVisible()
  await expect(page.getByText('Settled paper trades: 0',{exact:false})).toBeVisible()
  await expect(page.getByText('NFL contract evidence · Kalshi')).toBeVisible()
  await expect(page.locator('article').first()).toContainText('RESEARCH ONLY')
  await expect(page.getByText('Current terms reviewed: 48 / 48',{exact:false})).toBeVisible()
  await expect(page.getByText('Research model comparison · no validated edge')).toBeVisible()
  await expect(page.getByText('Selective value test: 0 qualifying selections in 1669 games',{exact:false})).toBeVisible()
  await expect(page.getByRole('cell',{name:'Opponent-adjusted EPA',exact:true})).toBeVisible()
  await expect(page.getByText('Independent model validation: advantage not demonstrated')).toBeVisible()
  await expect(page.getByText('Books observed: 48',{exact:false})).toBeVisible()
  await expect(page.locator('article').first()).toContainText('Implied yes ask:')
  await page.getByRole('button',{name:/Polymarket \(/}).click()
  await expect(page.getByText('NFL contract evidence · Polymarket')).toBeVisible()
  await expect(page.locator('article').first()).toContainText('Displayed outcomes:')
  await expect(page.getByText('Current terms reviewed: 22 / 22',{exact:false})).toBeVisible()
  await expect(page.getByText('Documented fee calculations checked: 22',{exact:false})).toBeVisible()
  await expect(page.getByText('Token books observed:',{exact:false})).toBeVisible()
  await expect(page.getByText('Postponement terms differ between providers.',{exact:false})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.getByLabel('Search observed markets').fill('unlikely-team-no-match')
  await expect(page.getByText('No matching observations in this view.')).toBeVisible()
 })
}
